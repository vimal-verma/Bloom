// Helper to compute pregnancy stats from LMP
export function computeFromLMP(lmpDateStr, cycleLength = 28) {
  const lmp = new Date(lmpDateStr + "T00:00:00");
  if (isNaN(lmp.getTime())) return null;

  // EDD is LMP + 280 days (adjusted for cycle length: 280 + (cycleLength - 28))
  const adjustment = (cycleLength - 28) * 24 * 60 * 60 * 1000;
  const edd = new Date(lmp.getTime() + 280 * 24 * 60 * 60 * 1000 + adjustment);

  return computeStats(lmp, edd);
}

// Helper to compute pregnancy stats from EDD
export function computeFromEDD(eddDateStr) {
  const edd = new Date(eddDateStr + "T00:00:00");
  if (isNaN(edd.getTime())) return null;

  // LMP is EDD - 280 days
  const lmp = new Date(edd.getTime() - 280 * 24 * 60 * 60 * 1000);
  return computeStats(lmp, edd);
}

function computeStats(lmp, edd) {
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  const diffMs = today.getTime() - lmp.getTime();
  const totalDaysPregnant = Math.floor(diffMs / (24 * 60 * 60 * 1000));

  const daysLeftMs = edd.getTime() - today.getTime();
  const daysLeft = Math.ceil(daysLeftMs / (24 * 60 * 60 * 1000));

  // Pregnancy weeks & days
  const currentWeek = Math.max(1, Math.min(42, Math.floor(totalDaysPregnant / 7) + 1));
  const currentDayOfWeek = totalDaysPregnant >= 0 ? (totalDaysPregnant % 7) : 0;

  // Trimester
  let trimester = 1;
  if (currentWeek >= 14 && currentWeek <= 27) trimester = 2;
  else if (currentWeek >= 28) trimester = 3;

  // Percentage complete (out of 280 days)
  const progressPercent = Math.max(0, Math.min(100, Math.round((totalDaysPregnant / 280) * 100)));

  // Lookup weekly info
  const weekInfo = WEEKS_DATA.find((w) => w.week === Math.min(40, currentWeek)) || WEEKS_DATA[39];

  return {
    lmpDate: lmp.toISOString().split("T")[0],
    eddDate: edd.toISOString().split("T")[0],
    totalDaysPregnant,
    currentWeek,
    currentDayOfWeek,
    daysLeft: Math.max(0, daysLeft),
    trimester,
    progressPercent,
    weekInfo,
    isOverdue: daysLeft < 0,
    isFuture: totalDaysPregnant < 0
  };
}

